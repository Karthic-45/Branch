"""Branch-scoped semantic retrieval.

One indexed approximate-nearest-neighbour query, restricted to a branch's
lineage, then a horizon and shadowing pass in Python.

This is the part no external vector store reproduces. When a branch searches, it
searches its own conclusions plus inherited memory frozen at the fork -- it
cannot reach a sibling's reasoning, because that reasoning lives on a branch
outside its lineage.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from decimal import Decimal
from typing import Any

import psycopg

from bmem.branch import AncestorScope, resolve_ancestry
from bmem.db import Vector

__all__ = ["Candidate", "Hit", "explain_search", "search", "select_visible"]

# The index returns nearest neighbours over the whole lineage, but some of those
# rows are then dropped: written after the querying branch forked, or shadowed by
# a nearer ancestor, or tombstoned. Over-fetch so the final top-k is still full.
#
# 4x is empirical headroom, not a guarantee. A branch that has tombstoned most of
# what it inherited could still come up short; search() reports when that happens
# rather than silently returning a thin result.
_OVERFETCH = 4

# How many index partitions CockroachDB's approximate search explores. The
# server default is tuned for latency, and on a freshly bulk-loaded index (the
# first real ingest of a whole repository, 1,540 rows written in quick batches
# while the index was still splitting partitions in the background) it
# returned zero rows for three of four branches -- so Claude was asked to
# write patches against code it was never shown. A wider beam trades a little
# latency for recall; the exact fallback below covers whatever is still missed.
_BEAM_SIZE = 256


@dataclass(frozen=True, slots=True)
class Candidate:
    """A row returned by the index, before visibility rules are applied."""

    branch_id: str
    key: str
    content: str | None
    created_at_hlc: str
    tombstone: bool
    distance: float


@dataclass(frozen=True, slots=True)
class Hit:
    """A memory the querying branch is actually entitled to see."""

    key: str
    content: str | None
    distance: float
    # Which branch the value came from -- the querying branch itself, or the
    # ancestor it was inherited from. Useful for the audit surface.
    source_branch_id: str
    inherited: bool


# branch_id placeholders are generated by count, never by interpolating values.
#
# An explicit IN (%s, %s, ...) rather than = ANY(%s): CockroachDB accelerates a
# filtered vector search only when each prefix column is constrained by = or IN,
# and the IN form is the one the docs name. Verified against EXPLAIN by
# explain_search() below -- if this ever degrades to a full scan, the isolation
# is still correct but the performance story is not.
_SEARCH_SQL = """
SELECT branch_id, key, content, created_at_hlc, tombstone,
       embedding <-> %(query)s AS distance
FROM memory
WHERE branch_id IN ({placeholders})
ORDER BY embedding <-> %(query)s
LIMIT %(limit)s
"""


# The same query forced onto the primary key, i.e. an exact scan of the
# lineage's rows instead of the approximate vector index. Used only as a
# fallback when the index comes back short.
_EXACT_SQL = _SEARCH_SQL.replace("FROM memory\n", "FROM memory@primary\n")


def _build_query(scopes: Sequence[AncestorScope], *, exact: bool = False) -> str:
    placeholders = ", ".join(f"%(b{i})s" for i in range(len(scopes)))
    return (_EXACT_SQL if exact else _SEARCH_SQL).format(placeholders=placeholders)


def _build_params(
    scopes: Sequence[AncestorScope], query_vector: Sequence[float], limit: int
) -> dict[str, Any]:
    params: dict[str, Any] = {"query": Vector(query_vector), "limit": limit}
    for i, scope in enumerate(scopes):
        params[f"b{i}"] = scope.branch_id
    return params


def select_visible(
    candidates: Sequence[Candidate], scopes: Sequence[AncestorScope], k: int
) -> list[Hit]:
    """Apply visibility rules to raw index output. Pure function.

    Three rules, in order:

    1. **Horizon.** A row from an ancestor is inherited only if it was written at
       or before the fork point on the path to us. Anything the ancestor wrote
       afterwards is invisible -- that is what makes a branch immune to its
       parent's later conclusions.
    2. **Shadowing.** When several branches in the lineage hold the same key, the
       nearest one wins. A branch's own value overrides what it inherited.
    3. **Tombstones.** A tombstone must win rule 2 before it takes effect, then
       removes the key entirely.

    Rule 3 is why tombstones are not filtered in SQL. Dropping them in the WHERE
    clause would remove the shadowing row and let the ancestor's live value
    through -- branch-local deletion would silently do nothing.
    """
    scope_by_branch = {s.branch_id: s for s in scopes}

    best: dict[str, tuple[Candidate, AncestorScope]] = {}
    for candidate in candidates:
        scope = scope_by_branch.get(candidate.branch_id)
        if scope is None:
            continue  # outside this lineage entirely
        if not scope.admits(candidate.created_at_hlc):
            continue  # written after we forked away
        current = best.get(candidate.key)
        if current is None or scope.depth < current[1].depth:
            best[candidate.key] = (candidate, scope)

    hits = [
        Hit(
            key=candidate.key,
            content=candidate.content,
            distance=candidate.distance,
            source_branch_id=candidate.branch_id,
            inherited=scope.depth > 0,
        )
        for candidate, scope in best.values()
        if not candidate.tombstone
    ]
    hits.sort(key=lambda h: h.distance)
    return hits[:k]


class _AncestryCache:
    """Per-branch ancestry, cached for the process lifetime.

    Safe to cache indefinitely: a branch's parent and fork point are written once
    at creation and never updated, so its lineage and horizons are immutable.
    """

    def __init__(self) -> None:
        self._cache: dict[str, list[AncestorScope]] = {}

    def get(self, cur: psycopg.Cursor[Any], branch_id: str) -> list[AncestorScope]:
        cached = self._cache.get(branch_id)
        if cached is None:
            cached = resolve_ancestry(cur, branch_id)
            if not cached:
                raise LookupError(f"no such branch: {branch_id}")
            self._cache[branch_id] = cached
        return cached

    def clear(self) -> None:
        self._cache.clear()


ancestry_cache = _AncestryCache()


def _widen_beam(cur: psycopg.Cursor[Any]) -> None:
    """Raise the ANN beam for this transaction, if the server knows the setting.

    current_setting(..., true) returns NULL instead of erroring on a server
    without vector_search_beam_size, so this never aborts the transaction.
    """
    cur.execute("SELECT current_setting('vector_search_beam_size', true) AS v")
    row = cur.fetchone()
    if row and row["v"] is not None:
        cur.execute(f"SET LOCAL vector_search_beam_size = {int(_BEAM_SIZE)}")


def search(
    cur: psycopg.Cursor[Any],
    branch_id: str,
    query_vector: Sequence[float],
    k: int = 8,
    *,
    mode: str = "auto",
) -> list[Hit]:
    """Semantic search over exactly one branch's belief state.

    ``mode``: ``"ann"`` uses the vector index only, ``"exact"`` scans the
    lineage exactly, and ``"auto"`` (the default) uses the index and falls back
    to an exact scan when the index returns fewer than ``k`` visible hits --
    an approximate index coming back short must not leave a branch reasoning
    with no context.
    """
    if mode not in ("auto", "ann", "exact"):
        raise ValueError(f"unknown search mode: {mode}")
    scopes = ancestry_cache.get(cur, branch_id)
    if mode != "exact":
        _widen_beam(cur)
        hits = _run(cur, scopes, query_vector, k, exact=False)
        if mode == "ann" or len(hits) >= k:
            return hits
    return _run(cur, scopes, query_vector, k, exact=True)


def _run(
    cur: psycopg.Cursor[Any],
    scopes: Sequence[AncestorScope],
    query_vector: Sequence[float],
    k: int,
    *,
    exact: bool,
) -> list[Hit]:
    cur.execute(
        _build_query(scopes, exact=exact), _build_params(scopes, query_vector, k * _OVERFETCH)
    )
    candidates = [
        Candidate(
            branch_id=str(row["branch_id"]),
            key=row["key"],
            content=row["content"],
            created_at_hlc=format(row["created_at_hlc"], "f")
            if isinstance(row["created_at_hlc"], Decimal)
            else str(row["created_at_hlc"]),
            tombstone=row["tombstone"],
            distance=float(row["distance"]),
        )
        for row in cur.fetchall()
    ]
    return select_visible(candidates, scopes, k)


def explain_search(
    cur: psycopg.Cursor[Any], branch_id: str, query_vector: Sequence[float], k: int = 8
) -> str:
    """Return the query plan for a branch-scoped search.

    Used by ``tests/test_index_usage.py`` to assert the vector index is actually
    being used and constrained by the ``branch_id`` prefix. If this ever shows a
    full table scan, retrieval still returns correct results but no longer scales
    -- and the central performance claim would be false.
    """
    scopes = ancestry_cache.get(cur, branch_id)
    cur.execute(
        "EXPLAIN (VERBOSE) " + _build_query(scopes),
        _build_params(scopes, query_vector, k * _OVERFETCH),
    )
    return "\n".join(str(row["info"]) for row in cur.fetchall())
